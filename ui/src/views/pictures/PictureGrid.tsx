import { useVirtualizer } from '@tanstack/react-virtual';
import { FileCode, ImageOff } from 'lucide-react';
import { useEffect, useRef, useState } from 'react';
import { useTranslation } from 'react-i18next';
import { useRendition } from '../../api/objectQueries';
import { hasRendition } from '../../api/objects';
import type { ObjectItem } from '../../api/types/ObjectItem';
import { cn } from '../../lib/cn';
import { formatBytes } from '../../lib/format';
import { useElementWidth } from '../../lib/useElementWidth';
import { displayName, typeLabel } from './format';

/** Grids longer than this are virtualized (docs/specs/pictures.md). */
export const VIRTUALIZE_FROM = 300;
/** Smallest tile width, in pixels (`minmax(140px, 1fr)`). */
const MIN_TILE = 140;
const GAP = 12;
/** Height of the caption under the square image area. */
const CAPTION = 40;
/** Height of the scrolling area of a virtualized grid. */
const VIRTUAL_HEIGHT = 720;
/** Images smaller than this (both sides) are shown at their size, not enlarged to the tile. */
const SMALL_IMAGE = 64;

interface PictureGridProps {
  sessionId: string;
  items: readonly ObjectItem[];
  onOpen: (index: number) => void;
}

/**
 * Regular grid of fixed-size tiles (ratio kept, centred crop, neutral background), each one a
 * button opening the viewer. Thumbnails are PNG files generated by the backend, fetched when the
 * tile comes into view. Long grids are virtualized by rows in their own scrolling area.
 */
export function PictureGrid({ sessionId, items, onOpen }: PictureGridProps) {
  const { t } = useTranslation();
  if (items.length > VIRTUALIZE_FROM) return <VirtualGrid sessionId={sessionId} items={items} onOpen={onOpen} />;
  return (
    <ul
      aria-label={t('views.pictures.gridLabel')}
      className="grid gap-3"
      style={{ gridTemplateColumns: `repeat(auto-fill, minmax(${MIN_TILE}px, 1fr))` }}
    >
      {items.map((item, index) => (
        <li key={item.sha256} className="min-w-0">
          <Tile
            sessionId={sessionId}
            item={item}
            onOpen={() => {
              onOpen(index);
            }}
          />
        </li>
      ))}
    </ul>
  );
}

function VirtualGrid({ sessionId, items, onOpen }: PictureGridProps) {
  const { t } = useTranslation();
  const scrollRef = useRef<HTMLDivElement>(null);
  const [widthRef, width] = useElementWidth();
  const usable = width > 0 ? width : 1280;
  const columns = Math.max(1, Math.floor((usable + GAP) / (MIN_TILE + GAP)));
  const tile = (usable - GAP * (columns - 1)) / columns;
  const rows = Math.ceil(items.length / columns);
  // eslint-disable-next-line react-hooks/incompatible-library -- TanStack Virtual is not memo-safe by design
  const virtualizer = useVirtualizer({
    count: rows,
    getScrollElement: () => scrollRef.current,
    estimateSize: () => tile + CAPTION + GAP,
    overscan: 2,
    // jsdom and the first render have no layout yet.
    initialRect: { width: usable, height: VIRTUAL_HEIGHT },
  });
  useEffect(() => {
    virtualizer.measure();
  }, [virtualizer, tile]);

  return (
    <div ref={widthRef} className="min-w-0">
      <div ref={scrollRef} className="overflow-y-auto overscroll-contain" style={{ maxHeight: VIRTUAL_HEIGHT }}>
        <ul aria-label={t('views.pictures.gridLabel')} className="relative" style={{ height: virtualizer.getTotalSize() }}>
          {virtualizer.getVirtualItems().flatMap((row) =>
            items.slice(row.index * columns, row.index * columns + columns).map((item, col) => {
              const index = row.index * columns + col;
              return (
                <li
                  key={item.sha256}
                  className="absolute top-0 left-0"
                  style={{ width: tile, transform: `translate(${col * (tile + GAP)}px, ${row.start}px)` }}
                >
                  <Tile
                    sessionId={sessionId}
                    item={item}
                    onOpen={() => {
                      onOpen(index);
                    }}
                  />
                </li>
              );
            }),
          )}
        </ul>
      </div>
    </div>
  );
}

/** True once the element has come near the viewport (always true without IntersectionObserver). */
function useInView(): [(el: HTMLElement | null) => void, boolean] {
  const [el, setEl] = useState<HTMLElement | null>(null);
  const [seen, setSeen] = useState(typeof IntersectionObserver === 'undefined');
  useEffect(() => {
    if (el === null || seen) return;
    const io = new IntersectionObserver(
      (entries) => {
        if (entries.some((e) => e.isIntersecting)) setSeen(true);
      },
      { rootMargin: '200px' },
    );
    io.observe(el);
    return () => {
      io.disconnect();
    };
  }, [el, seen]);
  return [setEl, seen];
}

interface TileProps {
  sessionId: string;
  item: ObjectItem;
  onOpen: () => void;
}

function Tile({ sessionId, item, onOpen }: TileProps) {
  const { t } = useTranslation();
  const [ref, inView] = useInView();
  const name = displayName(item);
  const size = formatBytes(item.size);
  const label = t('views.pictures.tile.label', { name, size });
  return (
    <button
      ref={ref}
      type="button"
      onClick={onOpen}
      aria-label={label}
      title={item.url ?? name}
      className="group flex w-full min-w-0 flex-col overflow-hidden rounded-md border border-line bg-surface text-left hover:border-accent focus-visible:border-accent"
    >
      <span className="relative flex aspect-square w-full items-center justify-center overflow-hidden bg-subtle">
        <TileImage sessionId={sessionId} item={item} enabled={inView} />
      </span>
      <span className="flex min-w-0 flex-col px-2 py-1" style={{ height: CAPTION }}>
        <span data-testid="truncatable" title={name} className="truncate text-meta">
          {name}
        </span>
        <span className="flex min-w-0 gap-2 text-meta text-muted">
          <span className="shrink-0">{typeLabel(item.mime)}</span>
          <span className="num truncate">{size}</span>
        </span>
      </span>
    </button>
  );
}

function TileImage({ sessionId, item, enabled }: { sessionId: string; item: ObjectItem; enabled: boolean }) {
  const { t } = useTranslation();
  const renderable = hasRendition(item);
  const thumb = useRendition(sessionId, item.sha256, 'thumb', enabled && renderable);
  if (!renderable || thumb.isError) {
    const svg = item.mime === 'image/svg+xml';
    const Icon = svg ? FileCode : ImageOff;
    return (
      <span className="flex flex-col items-center gap-1 px-2 text-center text-meta text-muted">
        <Icon aria-hidden size={24} strokeWidth={1.5} />
        {svg ? t('views.pictures.tile.svg') : t('views.pictures.tile.noPreview')}
      </span>
    );
  }
  if (thumb.data === undefined) return <span aria-hidden className="size-full animate-pulse bg-subtle" />;
  const small = item.width !== null && item.height !== null && item.width < SMALL_IMAGE && item.height < SMALL_IMAGE;
  return (
    <img
      src={thumb.data}
      alt=""
      draggable={false}
      className={cn(small ? 'max-h-full max-w-full object-contain' : 'size-full object-cover')}
      style={small ? { imageRendering: 'pixelated', width: (item.width ?? 0) * 2, height: (item.height ?? 0) * 2 } : undefined}
    />
  );
}
