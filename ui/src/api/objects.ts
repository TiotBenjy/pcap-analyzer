// Typed client of the objects routes (crates/netsift-api/src/objects.rs).
//
// Security: the webview only displays PNG files re-encoded by the backend (`thumb`, `preview`),
// fetched with the token and turned into `data:` URLs (allowed by the desktop CSP `img-src`;
// the token never appears in a URL). The original object is only ever downloaded as a file.

import { apiFetch, apiGet } from './client';
import type { PageParams } from './sessions';
import { attachmentName } from './tls';
import type { ObjectItem } from './types/ObjectItem';
import type { ObjectStats } from './types/ObjectStats';
import type { Page } from './types/Page';

/** Server-side filters of the picture list. */
export interface PictureFilters {
  /** Detected type (`image/png`). */
  type?: string | undefined;
  host?: string | undefined;
  /** Text in the host or the request target. */
  q?: string | undefined;
  /** `time` (first seen, default) or `size` (largest first). */
  sort?: 'time' | 'size' | undefined;
}

const objectsPath = (id: string): `/${string}` => `/sessions/${encodeURIComponent(id)}/objects`;
const objectPath = (id: string, sha256: string): `/${string}` =>
  `${objectsPath(id)}/${encodeURIComponent(sha256)}`;

function query(entries: Record<string, string | number | null | undefined>): string {
  const q = new URLSearchParams();
  for (const [key, value] of Object.entries(entries)) {
    if (value === undefined || value === null || value === '') continue;
    q.set(key, String(value));
  }
  const text = q.toString();
  return text === '' ? '' : `?${text}`;
}

export function getPictureStats(id: string, signal?: AbortSignal): Promise<ObjectStats> {
  return apiGet(`${objectsPath(id)}/stats?kind=image`, signal);
}

export function listPictures(
  id: string,
  filters: PictureFilters,
  params: PageParams = {},
  signal?: AbortSignal,
): Promise<Page<ObjectItem>> {
  const sort = filters.sort ?? 'time';
  const q = query({
    limit: params.limit,
    cursor: params.cursor,
    kind: 'image',
    sort,
    order: sort === 'size' ? 'desc' : 'asc',
    type: filters.type,
    host: filters.host,
    q: filters.q?.trim(),
  });
  return apiGet(`${objectsPath(id)}${q}`, signal);
}

/** True when the backend can render the object as a PNG (thumbnail, preview). */
export function hasRendition(item: Pick<ObjectItem, 'thumb'>): boolean {
  return item.thumb === 'ready' || item.thumb === 'pending';
}

function toDataUrl(blob: Blob): Promise<string> {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => {
      resolve(typeof reader.result === 'string' ? reader.result : '');
    };
    reader.onerror = () => {
      reject(reader.error ?? new Error('read failed'));
    };
    reader.readAsDataURL(blob);
  });
}

/**
 * A PNG rendition generated by the backend (`thumb`: 320 px, `preview`: 1600 px), as a
 * `data:image/png` URL. Anything but a PNG answer is refused.
 */
export async function fetchRendition(
  id: string,
  sha256: string,
  kind: 'thumb' | 'preview',
  signal?: AbortSignal,
): Promise<string> {
  const res = await apiFetch(`${objectPath(id, sha256)}/${kind}`, { accept: 'image/png', signal });
  if (res.headers.get('Content-Type') !== 'image/png') throw new Error('unexpected rendition type');
  const bytes = await res.arrayBuffer();
  return toDataUrl(new Blob([bytes], { type: 'image/png' }));
}

/**
 * Downloads the original object as a file: fetched with the token, then saved through a
 * temporary object URL. The content is never displayed by the webview.
 */
export async function downloadObject(id: string, item: Pick<ObjectItem, 'sha256' | 'file_name'>): Promise<void> {
  const res = await apiFetch(objectPath(id, item.sha256), { accept: '*/*' });
  const name = attachmentName(res.headers.get('Content-Disposition')) ?? item.file_name;
  const blob = new Blob([await res.arrayBuffer()], { type: 'application/octet-stream' });
  const url = URL.createObjectURL(blob);
  try {
    const a = document.createElement('a');
    a.href = url;
    a.download = name;
    a.rel = 'noopener';
    document.body.append(a);
    a.click();
    a.remove();
  } finally {
    setTimeout(() => {
      URL.revokeObjectURL(url);
    }, 1000);
  }
}
