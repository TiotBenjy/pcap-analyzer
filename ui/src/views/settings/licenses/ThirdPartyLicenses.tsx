import { useQuery } from '@tanstack/react-query';
import { ChevronDown, ChevronRight, Search } from 'lucide-react';
import { useDeferredValue, useMemo, useState } from 'react';
import { useTranslation } from 'react-i18next';
import { Badge } from '../../../components/Badge';
import { Button } from '../../../components/Button';
import { Dialog } from '../../../components/Dialog';
import { ErrorState } from '../../../components/ErrorState';
import { labelled } from '../../../lib/format';
import { type Group, groupPackages, loadLicenses } from './data';
import type { ThirdPartyLicenses, ThirdPartyPackage } from './types';

// Third-party licenses of the shipped application (generated by `./x.sh licenses`, never fetched):
// grouped by the license whose terms are reproduced, searchable, texts shown on demand as plain
// text nodes (never HTML).

export function ThirdPartyLicensesDialog({ onClose }: { onClose: () => void }) {
  const { t } = useTranslation();
  const [query, setQuery] = useState('');
  const deferred = useDeferredValue(query);
  const list = useQuery({ queryKey: ['third-party-licenses'], queryFn: loadLicenses, staleTime: Infinity, retry: false });
  const groups = useMemo(() => (list.data === undefined ? [] : groupPackages(list.data, deferred)), [list.data, deferred]);
  const shown = groups.reduce((n, g) => n + g.packages.length, 0);
  const searching = deferred.trim() !== '';

  let body;
  if (list.isError) {
    body = (
      <ErrorState
        message={t('views.settings.thirdParty.loadError')}
        onRetry={() => {
          void list.refetch();
        }}
      />
    );
  } else if (list.data === undefined) {
    body = <p className="text-muted">{t('common.loading')}</p>;
  } else {
    body = (
      <div className="flex min-w-0 flex-col gap-3">
        <label className="relative flex h-8 min-w-0 items-center sm:max-w-xs">
          <span className="sr-only">{t('views.settings.thirdParty.search')}</span>
          <Search aria-hidden size={16} strokeWidth={1.75} className="pointer-events-none absolute left-2.5 text-faint" />
          <input
            type="search"
            data-autofocus
            value={query}
            placeholder={t('views.settings.thirdParty.search')}
            onChange={(e) => {
              setQuery(e.target.value);
            }}
            className="h-8 w-full min-w-0 rounded-md border border-line bg-surface pr-2 pl-8 text-body placeholder:text-faint"
          />
        </label>
        <p className="text-meta text-muted" data-testid="licenses-count" aria-live="polite">
          {t('views.settings.thirdParty.shown', { shown, count: list.data.packages.length })}
        </p>
        {groups.length === 0 ? (
          <p className="text-muted">{t('views.settings.thirdParty.empty')}</p>
        ) : (
          <ul className="flex min-w-0 flex-col gap-2" aria-label={t('views.settings.thirdParty.title')}>
            {groups.map((g) => (
              // Remounted when a search starts or ends: groups open while searching, closed otherwise.
              <LicenseGroup key={`${g.license}:${String(searching)}`} group={g} data={list.data} defaultOpen={searching} />
            ))}
          </ul>
        )}
      </div>
    );
  }

  return (
    <Dialog open size="lg" onClose={onClose} title={t('views.settings.thirdParty.title')} description={t('views.settings.thirdParty.hint')}>
      {body}
    </Dialog>
  );
}

function LicenseGroup({ group, data, defaultOpen }: { group: Group; data: ThirdPartyLicenses; defaultOpen: boolean }) {
  const { t } = useTranslation();
  const [open, setOpen] = useState(defaultOpen);
  const Chevron = open ? ChevronDown : ChevronRight;
  return (
    <li className="min-w-0 rounded-md border border-line">
      <button
        type="button"
        aria-expanded={open}
        onClick={() => {
          setOpen(!open);
        }}
        className="flex min-h-8 w-full min-w-0 items-center gap-2 rounded-md px-2 py-1.5 text-left hover:bg-subtle"
      >
        <Chevron aria-hidden size={16} strokeWidth={1.75} className="shrink-0 text-faint" />
        <span className="min-w-0 flex-1 font-medium break-words">{group.license}</span>
        <span className="num shrink-0 text-meta text-muted">
          {t('views.settings.thirdParty.packages', { count: group.packages.length })}
        </span>
      </button>
      {open && (
        <ul className="flex min-w-0 flex-col border-t border-line" aria-label={group.license}>
          {group.packages.map((p) => (
            <PackageRow key={`${p.source}:${p.name}@${p.version}`} pkg={p} data={data} />
          ))}
        </ul>
      )}
    </li>
  );
}

function PackageRow({ pkg, data }: { pkg: ThirdPartyPackage; data: ThirdPartyLicenses }) {
  const { t } = useTranslation();
  const [open, setOpen] = useState(false);
  const id = `${pkg.source}:${pkg.name}@${pkg.version}`;
  return (
    <li className="flex min-w-0 flex-col gap-1 border-b border-line px-2 py-1.5 last:border-b-0" data-testid="license-package">
      <div className="flex min-w-0 flex-wrap items-center gap-x-2 gap-y-1">
        <span data-testid="truncatable" title={pkg.name} className="min-w-0 truncate font-mono text-table">
          {pkg.name}
        </span>
        <span className="font-mono text-meta text-muted">{pkg.version}</span>
        <Badge>{pkg.source === 'cargo' ? t('views.settings.thirdParty.rust') : t('views.settings.thirdParty.npm')}</Badge>
        <Button
          variant="ghost"
          className="ml-auto h-7 px-2 text-meta"
          aria-expanded={open}
          aria-controls={open ? id : undefined}
          onClick={() => {
            setOpen(!open);
          }}
        >
          {open ? t('views.settings.thirdParty.hideText') : t('views.settings.thirdParty.showText')}
        </Button>
      </div>
      {pkg.declared !== pkg.license && (
        <span className="break-words text-meta text-muted">{labelled(t('views.settings.thirdParty.declared'), pkg.declared)}</span>
      )}
      {open && (
        <div id={id} className="flex min-w-0 flex-col gap-2 pt-1">
          {pkg.reference === true && <p className="text-meta text-muted">{t('views.settings.thirdParty.reference')}</p>}
          {pkg.texts.map((i) => {
            const text = data.texts[i];
            if (text === undefined) return null;
            return (
              <section key={i} className="flex min-w-0 flex-col gap-1">
                <h3 className="text-meta font-medium break-words">{text.title}</h3>
                {/* Plain text node: React escapes it, nothing is interpreted as HTML. */}
                <pre className="max-h-80 min-w-0 overflow-auto rounded-md border border-line bg-subtle p-2 font-mono text-meta break-words whitespace-pre-wrap">
                  {text.text}
                </pre>
              </section>
            );
          })}
        </div>
      )}
    </li>
  );
}
