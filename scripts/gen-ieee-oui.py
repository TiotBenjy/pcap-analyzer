#!/usr/bin/env python3
"""Generates crates/netsift-analyze/data/ieee-oui.tsv from the IEEE Registration Authority listings.

Usage (on the host, Python 3 standard library only), the four CSV files downloaded into an empty
folder of their own:

    mkdir -p /tmp/ieee-oui && cd /tmp/ieee-oui
    curl -fsSLO https://standards-oui.ieee.org/oui/oui.csv
    curl -fsSLO https://standards-oui.ieee.org/oui28/mam.csv
    curl -fsSLO https://standards-oui.ieee.org/oui36/oui36.csv
    curl -fsSLO https://standards-oui.ieee.org/iab/iab.csv
    cd - && python3 -I scripts/gen-ieee-oui.py /tmp/ieee-oui crates/netsift-analyze/data/ieee-oui.tsv

The IEEE public listing (MA-L, MA-M, MA-S, IAB) is published for anyone to use: the IEEE does
not assert copyright in it nor restrict its distribution (ADR-031). Only the assignment and the
organization name are kept (never the postal address), in a compact format read by
`netsift_analyze::oui`:

    prefix<TAB>organization   prefix: 6 (MA-L, 24 bits), 7 (MA-M, 28 bits) or 9 (MA-S and IAB,
                              36 bits) upper-case hexadecimal digits
"""

import csv
import datetime
import os
import re
import sys

BASE = "https://standards-oui.ieee.org"
# File name -> (registry labels accepted in its first column, prefix length in hex digits).
FILES = {
    "oui.csv": ({"MA-L"}, 6),
    "mam.csv": ({"MA-M"}, 7),
    "oui36.csv": ({"MA-S"}, 9),
    "iab.csv": ({"IAB"}, 9),
}
SOURCES = ("oui/oui.csv", "oui28/mam.csv", "oui36/oui36.csv", "iab/iab.csv")
HEADER = ["Registry", "Assignment", "Organization Name", "Organization Address"]
CONTROL = re.compile(r"[\x00-\x1f\x7f]")
# Longest organization name kept, in characters (the longest one is about 110).
MAX_NAME = 128
# The real listings hold about 59 000 assignments: far fewer means a truncated or wrong file.
MIN_ENTRIES = 40_000


# Two-byte UTF-8 sequence read as Latin-1: lead byte 0xC2-0xDF, then a continuation byte.
MANGLED = re.compile("[\u00c2-\u00df][\u0080-\u00bf]")


def unmangle(name):
    """Repairs UTF-8 read as Latin-1 in a few listing entries: "AlmudÃ\u00ad" -> "Almudí"."""
    return MANGLED.sub(lambda m: m.group(0).encode("latin-1").decode("utf-8", "replace"), name)


def clean(name):
    name = CONTROL.sub(" ", unmangle(name))
    name = " ".join(name.split())
    return name[:MAX_NAME].rstrip()


def read(folder, file, registries, digits, names):
    path = os.path.join(folder, file)
    with open(path, newline="", encoding="utf-8") as f:
        rows = csv.reader(f)
        header = next(rows, None)
        if header is None or [h.strip() for h in header[:4]] != HEADER:
            sys.exit(f"{path}: unexpected header {header!r}")
        for row in rows:
            if len(row) < 3 or row[0].strip() not in registries:
                continue
            prefix = row[1].strip().upper()
            name = clean(row[2])
            if len(prefix) != digits or not re.fullmatch(r"[0-9A-F]+", prefix) or name == "":
                continue
            names.setdefault(prefix, set()).add(name)


def main(folder, dst):
    names = {}  # prefix -> organization names (a few MA-L blocks were assigned twice)
    for file, (registries, digits) in FILES.items():
        read(folder, file, registries, digits, names)
    if len(names) < MIN_ENTRIES:
        sys.exit(f"only {len(names)} assignments: incomplete listings?")

    today = datetime.date.today().isoformat()
    with open(dst, "w", encoding="utf-8", newline="\n") as out:
        out.write(
            "# IEEE Registration Authority public listings: MA-L, MA-M, MA-S and IAB assignments.\n"
            f"# Sources: {', '.join(f'{BASE}/{s}' for s in SOURCES)}\n"
            f"# Retrieved: {today}\n"
            "# The IEEE does not assert copyright in the public listing nor restrict its distribution (ADR-031).\n"
            "# Organization names only. Generated by scripts/gen-ieee-oui.py: do not edit by hand.\n"
            "# Format: prefix<TAB>organization; prefix = 6 (MA-L), 7 (MA-M) or 9 (MA-S, IAB) hex digits.\n"
        )
        for prefix in sorted(names, key=lambda p: (len(p), p)):
            out.write(f"{prefix}\t{' / '.join(sorted(names[prefix]))}\n")
    print(f"{len(names)} assignments -> {dst}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("usage: gen-ieee-oui.py <folder with oui.csv mam.csv oui36.csv iab.csv> <output.tsv>")
    main(sys.argv[1], sys.argv[2])
