//! `netsift` command-line entry point.

use std::net::SocketAddr;
use std::path::PathBuf;

use anyhow::{Context, Result, bail};
use clap::{Args, Parser, Subcommand};
use netsift_api::ApiConfig;
use tracing::{info, warn};

#[derive(Debug, Parser)]
#[command(
    name = "netsift",
    version,
    about = "Forensic analysis of network captures"
)]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Debug, Subcommand)]
enum Command {
    /// Serve the HTTP API (used by `./x.sh dev`, screenshots, and for debugging with curl).
    Serve(ServeArgs),
}

#[derive(Debug, Args)]
struct ServeArgs {
    /// Address to bind. Keep it on loopback outside a container.
    #[arg(long, default_value = "127.0.0.1:7878")]
    bind: SocketAddr,
    /// Bearer token (prefer --token-file: arguments are visible in the process list).
    #[arg(
        long,
        env = "NETSIFT_TOKEN",
        hide_env_values = true,
        conflicts_with = "token_file"
    )]
    token: Option<String>,
    /// File containing the bearer token (surrounding whitespace is ignored).
    #[arg(long)]
    token_file: Option<PathBuf>,
    /// Application data directory (catalog and sessions).
    #[arg(long, default_value = ".data")]
    data_dir: PathBuf,
    /// Folder the web folder browser may list; repeatable.
    #[arg(long = "captures-root")]
    captures_roots: Vec<PathBuf>,
    /// Disable every mutating route.
    #[arg(long)]
    read_only: bool,
}

/// Minimum token length: tokens are generated by scripts or the desktop app, never typed.
const MIN_TOKEN_LEN: usize = 16;

fn resolve_token(args: &ServeArgs) -> Result<String> {
    let token = match (&args.token, &args.token_file) {
        (Some(t), _) => t.trim().to_owned(),
        (None, Some(path)) => std::fs::read_to_string(path)
            .with_context(|| format!("cannot read token file {}", path.display()))?
            .trim()
            .to_owned(),
        (None, None) => bail!("a token is required: --token-file <path>, --token or NETSIFT_TOKEN"),
    };
    if token.len() < MIN_TOKEN_LEN {
        bail!("token too short: at least {MIN_TOKEN_LEN} characters required");
    }
    Ok(token)
}

async fn serve(args: ServeArgs) -> Result<()> {
    let token = resolve_token(&args)?;
    if !args.bind.ip().is_loopback() {
        warn!(bind = %args.bind, "binding a non-loopback address; only do this inside a container");
    }
    std::fs::create_dir_all(&args.data_dir)
        .with_context(|| format!("cannot create data directory {}", args.data_dir.display()))?;

    let listener = tokio::net::TcpListener::bind(args.bind)
        .await
        .with_context(|| format!("cannot bind {}", args.bind))?;
    info!(addr = %listener.local_addr()?, read_only = args.read_only, "API listening");

    let config = ApiConfig {
        token,
        data_dir: args.data_dir,
        captures_roots: args.captures_roots,
        read_only: args.read_only,
        cors_origins: Vec::new(),
    };
    netsift_api::serve(listener, config, shutdown_signal()).await?;
    info!("API stopped");
    Ok(())
}

/// Resolves on Ctrl-C or SIGTERM (container stop).
async fn shutdown_signal() {
    let ctrl_c = async {
        let _ = tokio::signal::ctrl_c().await;
    };
    #[cfg(unix)]
    let term = async {
        match tokio::signal::unix::signal(tokio::signal::unix::SignalKind::terminate()) {
            Ok(mut s) => {
                s.recv().await;
            }
            Err(_) => std::future::pending::<()>().await,
        }
    };
    #[cfg(not(unix))]
    let term = std::future::pending::<()>();
    tokio::select! {
        () = ctrl_c => {},
        () = term => {},
    }
}

fn main() -> Result<()> {
    tracing_subscriber::fmt()
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| "info,tower_http=warn".into()),
        )
        .with_writer(std::io::stderr)
        .init();

    let cli = Cli::parse();
    let runtime = tokio::runtime::Builder::new_multi_thread()
        .enable_all()
        .build()?;
    match cli.command {
        Command::Serve(args) => runtime.block_on(serve(args)),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use clap::CommandFactory;

    fn parse(args: &[&str]) -> ServeArgs {
        let cli = Cli::try_parse_from(args).unwrap();
        let Command::Serve(serve) = cli.command;
        serve
    }

    #[test]
    fn cli_definition_is_valid() {
        Cli::command().debug_assert();
    }

    #[test]
    fn serve_defaults_to_loopback() {
        let a = parse(&["netsift", "serve", "--token", "0123456789abcdef"]);
        assert!(a.bind.ip().is_loopback());
        assert!(!a.read_only);
    }

    #[test]
    fn token_rules() {
        let short = parse(&["netsift", "serve", "--token", "short"]);
        assert!(resolve_token(&short).is_err());

        let dir = std::env::temp_dir().join(format!("netsift-cli-test-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let file = dir.join("token");
        std::fs::write(&file, "  0123456789abcdef0123\n").unwrap();
        let from_file = parse(&["netsift", "serve", "--token-file", file.to_str().unwrap()]);
        assert_eq!(resolve_token(&from_file).unwrap(), "0123456789abcdef0123");
        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn token_and_token_file_conflict() {
        assert!(
            Cli::try_parse_from(["netsift", "serve", "--token", "x", "--token-file", "y"]).is_err()
        );
    }
}
