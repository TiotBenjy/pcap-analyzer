#!/usr/bin/env python3
"""Generates crates/netsift-analyze/data/iana-services.csv from the IANA registry.

Usage (on the host, Python 3 standard library only):

    curl -fsSLo /tmp/iana/services.csv \
      https://www.iana.org/assignments/service-names-port-numbers/service-names-port-numbers.csv
    python3 -I scripts/gen-iana-services.py /tmp/iana/services.csv \
      crates/netsift-analyze/data/iana-services.csv

The registry is dedicated to the public domain (CC0 1.0, joint IANA/IETF statement of
2021-11-10, https://www.iana.org/help/licensing-terms). Only TCP and UDP assignments with a
service name are kept, first name per (port, transport), in a compact format read by
`netsift_analyze::services`:

    port,transports,name      transports: b = TCP and UDP, t = TCP only, u = UDP only
"""

import csv
import datetime
import re
import sys

SOURCE = "https://www.iana.org/assignments/service-names-port-numbers/service-names-port-numbers.csv"
NAME = re.compile(r"^[a-z0-9][a-z0-9.+_-]{0,31}$")
# Assigned ranges (x11 6000-6063...) are expanded up to this many ports.
MAX_RANGE = 128


def ports(field):
    field = field.strip()
    if re.fullmatch(r"\d+", field):
        return [int(field)]
    m = re.fullmatch(r"(\d+)-(\d+)", field)
    if m:
        lo, hi = int(m.group(1)), int(m.group(2))
        if 0 <= lo <= hi and hi - lo < MAX_RANGE:
            return list(range(lo, hi + 1))
    return []


def main(src, dst):
    names = {}  # (port, transport) -> name
    with open(src, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            name = (row.get("Service Name") or "").strip().lower()
            transport = (row.get("Transport Protocol") or "").strip().lower()
            if transport not in ("tcp", "udp") or not NAME.match(name):
                continue
            for port in ports(row.get("Port Number") or ""):
                if 0 < port <= 65535:
                    names.setdefault((port, transport), name)

    lines = []
    for port in sorted({p for p, _ in names}):
        tcp, udp = names.get((port, "tcp")), names.get((port, "udp"))
        if tcp is not None and tcp == udp:
            lines.append(f"{port},b,{tcp}")
            continue
        if tcp is not None:
            lines.append(f"{port},t,{tcp}")
        if udp is not None:
            lines.append(f"{port},u,{udp}")

    today = datetime.date.today().isoformat()
    with open(dst, "w", encoding="ascii", newline="\n") as out:
        out.write(
            "# IANA Service Name and Transport Protocol Port Number Registry: TCP and UDP.\n"
            f"# Source: {SOURCE}\n"
            f"# Retrieved: {today}\n"
            "# License: CC0 1.0 (IANA/IETF joint statement, https://www.iana.org/help/licensing-terms)\n"
            "# Generated by scripts/gen-iana-services.py: do not edit by hand.\n"
            "# Format: port,transports,name (b = tcp and udp, t = tcp only, u = udp only)\n"
        )
        for line in lines:
            out.write(line + "\n")
    print(f"{len(lines)} lines, {len(names)} (port, transport) names -> {dst}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("usage: gen-iana-services.py <registry.csv> <output.csv>")
    main(sys.argv[1], sys.argv[2])
